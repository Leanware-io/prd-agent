import uuid

# pylint: disable=R0903
from django.db import models

from api.users.models import User
from prd_agent.base_model import BaseModel


def generate_session_key():
    """Generate a unique session key"""
    return str(uuid.uuid4())


class Session(BaseModel):
    """
    A session is a session that is created when a user starts a chat with the AI.
    """

    user = models.ForeignKey(
        User, on_delete=models.CASCADE, null=True, related_name="sessions"
    )
    session_key = models.CharField(
        max_length=255, unique=True, default=generate_session_key
    )
    status = models.CharField(max_length=50, blank=True, null=True, default=None)
    has_contacted_leanware = models.BooleanField(default=False)


class Quote(BaseModel):
    """
    A quote is a PDF file that is generated by the
    assistant during the session and the quote generation process.
    """

    session = models.ForeignKey(Session, on_delete=models.CASCADE)
    quote_pdf_path = models.CharField(max_length=255, unique=True)
